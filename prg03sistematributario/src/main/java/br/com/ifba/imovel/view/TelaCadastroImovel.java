    // Método para preencher o ComboBox com dados do banco
    public void carregarComboBoxContribuintes() {
        cmbContribuinte.removeAllItems(); // Limpa itens antigos
        List<Contribuinte> listaContribuintes = contribuinteController.findByAtivoTrue();
        
        for (Contribuinte c : listaContribuintes) {
            Long id = c.getId();
            String nome = c.getNome();
    
            //  o objeto que vai para o ComboBox usando essas variáveis
            ContribuinteItem item = new ContribuinteItem(id, nome);
   
            //o item pronto vai para o ComboBox
            cmbContribuinte.addItem(item);
        }
    }
    
    public void setModo(String modo, Long id, GerenciarImoveis principal) {
        this.modo = modo;
        this.idEmEdicao = id;
        this.telaPrincipal = principal;
        
        lblTitulo.setText(modo.equals("EDITAR") ? "EDITAR IMÓVEL" : "CADASTRAR IMÓVEL");
        
        // Sempre carrega o combobox quando a tela for aberta
        carregarComboBoxContribuintes();
 
        if (modo.equals("SALVAR")) {
            limparCampos();
        }
    }
    
    public void preencherCampos(Imovel i) {
        txtInscricao.setText(i.getInscricaoImobiliaria());
        txtAreaTerreno.setText(String.valueOf(i.getAreaTerreno()));
        txtAreaConstruida.setText(String.valueOf(i.getAreaConstruida()));
        txtValorVenal.setText(String.valueOf(i.getValorVenal()));
 
        // Seleciona o contribuinte dono no ComboBox pelo ID
        if (i.getContribuinte() != null) {
            for (int idx = 0; idx < cmbContribuinte.getItemCount(); idx++) {
                ContribuinteItem item = (ContribuinteItem) cmbContribuinte.getItemAt(idx);
                if (item.getId().equals(i.getContribuinte().getId())) {
                    cmbContribuinte.setSelectedIndex(idx);
                    break;
                }
            }
            
        }
 
        // Preenche os campos de endereço
        if (i.getEndereco() != null) {
            Endereco end = i.getEndereco();
            txtLogradouro.setText(end.getLogradouro());
            txtNumero.setText(end.getNumero());
            txtComplemento.setText(end.getComplemento() != null ? end.getComplemento() : "");
            txtBairro.setText(end.getBairro());
            txtCidade.setText(end.getCidade());
            cmbEstado.setSelectedItem(end.getEstado());
            txtCep.setText(end.getCep());
        }
    }

    private void limparCampos() {
        txtInscricao.setText("");
        txtAreaTerreno.setText("");
        txtAreaConstruida.setText("");
        txtValorVenal.setText("");
        txtLogradouro.setText("");
        txtNumero.setText("");
        txtComplemento.setText("");
        txtBairro.setText("");
        txtCidade.setText("");
        txtCep.setText("");
        if(cmbContribuinte.getItemCount() > 0) cmbContribuinte.setSelectedIndex(0);
        cmbEstado.setSelectedIndex(0);
    }
