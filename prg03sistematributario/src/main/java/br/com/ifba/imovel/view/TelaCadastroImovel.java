    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        try {
            // 1. Validar se um contribuinte foi selecionado
            ContribuinteItem itemSelecionado = (ContribuinteItem) cmbContribuinte.getSelectedItem();
            if (itemSelecionado == null) {
                JOptionPane.showMessageDialog(this, "Por favor, selecione um contribuinte.", "Erro", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 2. Monta o objeto Endereco
            Endereco endereco = new Endereco();
            endereco.setLogradouro(txtLogradouro.getText());
            endereco.setNumero(txtNumero.getText());
            endereco.setComplemento(txtComplemento.getText());
            endereco.setBairro(txtBairro.getText());
            endereco.setCidade(txtCidade.getText());
            endereco.setEstado((String) cmbEstado.getSelectedItem());
            endereco.setCep(txtCep.getText());
 
            // 3. Monta o objeto Imovel
            Imovel dados = new Imovel();
            dados.setInscricaoImobiliaria(txtInscricao.getText());
            dados.setEndereco(endereco);
            
            // --- INÍCIO DOS IFS EXPANDIDOS PARA CONVERSÃO DE NÚMEROS ---
            
            // Área Terreno
            if (txtAreaTerreno.getText().isEmpty()) {
                dados.setAreaTerreno(0.0);
            } else {
                dados.setAreaTerreno(Double.parseDouble(txtAreaTerreno.getText()));
            }

            // Área Construída
            if (txtAreaConstruida.getText().isEmpty()) {
                dados.setAreaConstruida(0.0);
            } else {
                dados.setAreaConstruida(Double.parseDouble(txtAreaConstruida.getText()));
            }

            // Valor Venal
            dados.setValorVenal(dados.calcularValorVenal());
            
            // --- FIM DAS CONVERSÕES ---
            
            // 4. Associa o Contribuinte ao Imóvel
            Contribuinte dono = contribuinteController.findById(itemSelecionado.getId());
            dados.setContribuinte(dono);
 
            // 5. CAIXA DE CONFIRMAÇÃO ANTES DE SALVAR COM IF/ELSE
            String mensagem;
            if (modo.equals("EDITAR")) {
                mensagem = "Tem certeza que deseja salvar as alterações neste imóvel?";
            } else {
                mensagem = "Tem certeza que deseja cadastrar este novo imóvel?";
            }
            
            int resposta = JOptionPane.showConfirmDialog(
                    this, 
                    mensagem, 
                    "Confirmar Ação", 
                    JOptionPane.YES_NO_OPTION, 
                    JOptionPane.QUESTION_MESSAGE
            );

            // Se o usuário clicar em "Não" (NO_OPTION) ou fechar a janela, cancelamos a ação
            if (resposta != JOptionPane.YES_OPTION) {
                return; 
            }

            //  Decide entre Salvar e Atualizar
            if (modo.equals("EDITAR") && idEmEdicao != null) {
                imovelController.update(idEmEdicao, dados);
                JOptionPane.showMessageDialog(this, "Imóvel atualizado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            } else {
                imovelController.save(dados);
                JOptionPane.showMessageDialog(this, "Imóvel cadastrado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            }
 
            limparCampos();
            telaPrincipal.carregarTabela();
            this.dispose();
 
        } catch (NumberFormatException e) {
             JOptionPane.showMessageDialog(this, "Certifique-se de digitar números válidos nas áreas e valor venal.", "Erro de Digitação", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            log.warn("Erro ao salvar imóvel: {}", ex.getMessage());
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro ao Salvar", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

