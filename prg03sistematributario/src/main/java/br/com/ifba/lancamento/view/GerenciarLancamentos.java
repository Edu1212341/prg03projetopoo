    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        int linha = tblLancamentos.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um lançamento na tabela para excluir.",
                    "Nenhuma seleção", JOptionPane.WARNING_MESSAGE);
            return;
        }
 
        Long   id        = (Long)   tblLancamentos.getValueAt(linha, 4);
        String inscricao = (String) tblLancamentos.getValueAt(linha, 0);
 
        int confirmacao = JOptionPane.showConfirmDialog(this,
                "Tem certeza que deseja inativar o lançamento do imóvel:\n\"" + inscricao + "\"?",
                "Confirmar Exclusão", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
 
        if (confirmacao == JOptionPane.YES_OPTION) {
            try {
                lancamentoController.delete(id);
                JOptionPane.showMessageDialog(this,
                        "Lançamento inativado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                tblLancamentos.clearSelection();
                carregarTabela();
            } catch (Exception ex) {
                log.error("Erro ao excluir lançamento ID {}: {}", id, ex.getMessage());
                JOptionPane.showMessageDialog(this,
                        ex.getMessage(), "Erro ao Excluir", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        int linha = tblLancamentos.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um lançamento na tabela para editar.",
                    "Nenhuma seleção", JOptionPane.WARNING_MESSAGE);
            return;
        }
 
        Long id = (Long) tblLancamentos.getValueAt(linha, 4);
        LancamentoImposto lancamento = lancamentoController.findById(id);
 
        telaCadastro.setModo("EDITAR", id, this);
        telaCadastro.preencherCampos(lancamento);
        telaCadastro.setVisible(true);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String texto = txtBuscar.getText().trim();
 
        if (texto.isEmpty()) {
            carregarTabela();
            return;
        }
 
        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel) tblLancamentos.getModel();
        modelo.setRowCount(0);
 
        try {
            for (LancamentoImposto l : lancamentoController.findByAtivoTrue()) {
 
                String inscricao;
                if (l.getImovel() != null) {
                    inscricao = l.getImovel().getInscricaoImobiliaria();
                } else {
                    inscricao = "";
                }
 
                String imposto;
                if (l.getImposto() != null) {
                    imposto = l.getImposto().getDescricao();
                } else {
                    imposto = "";
                }
 
                String ano = String.valueOf(l.getAno());
 
                boolean correspondeInscricao = inscricao.toLowerCase().contains(texto.toLowerCase());
                boolean correspondeImposto   = imposto.toLowerCase().contains(texto.toLowerCase());
                boolean correspondeAno       = ano.contains(texto);
 
                if (correspondeInscricao || correspondeImposto || correspondeAno) {
                    modelo.addRow(new Object[]{
                        inscricao,
                        imposto,
                        ano,
                        String.format("R$ %.2f", l.getValorTotalCalculado()),
                        l.getId()
                    });
                }
            }
 
            if (modelo.getRowCount() == 0) {
                JOptionPane.showMessageDialog(this,
                        "Nenhum lançamento encontrado para: \"" + texto + "\".",
                        "Busca sem resultado", JOptionPane.INFORMATION_MESSAGE);
            }
 
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao buscar: " + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed
    @Override
    public void setVisible(boolean visible) {
        if (visible) {
            Usuario logado = sessaoService.getUsuarioLogado();
            
            // Se NÃO for ADMIN, o botão de inativar/excluir fica cinza (desabilitado)
            if (logado != null && !logado.getNivelAcesso().equals("ADMIN")) {
                btnExcluir.setEnabled(false);
                btnExcluir.setToolTipText("Apenas administradores podem inativar lançamentos.");
            } else {
                btnExcluir.setEnabled(true);
            }
        }
        super.setVisible(visible);
    }
