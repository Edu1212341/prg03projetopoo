    public void carregarTabela(){
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblLancamentos.getModel();
        modelo.setRowCount(0);
 
        try {
            for (LancamentoImposto l : lancamentoController.findByAtivoTrue()) {
 
                String inscricao;
                if (l.getImovel() != null) {
                    inscricao = l.getImovel().getInscricaoImobiliaria();
                } else {
                    inscricao = "-";
                }
 
                String imposto;
                if (l.getImposto() != null) {
                    imposto = l.getImposto().getDescricao();
                } else {
                    imposto = "-";
                }
 
                String valorFormatado = String.format("R$ %.2f", l.getValorTotalCalculado());
 
                modelo.addRow(new Object[]{
                    inscricao,
                    imposto,
                    String.valueOf(l.getAno()),
                    valorFormatado,
                    l.getId() 
                });
            }
        } catch (Exception e) {
            log.error("Erro ao carregar tabela de lançamentos: {}", e.getMessage());
            JOptionPane.showMessageDialog(this, "Erro ao carregar tabela: " + e.getMessage());
        }
    }
