    public void setModo(String modo, Long id, GerenciarLancamentos principal) {
        this.modo          = modo;
        this.idEmEdicao    = id;
        this.telaPrincipal = principal;
 
        if (modo.equals("EDITAR")) {
            lblTitulo.setText("EDITAR LANÇAMENTO");
        } else {
            lblTitulo.setText("NOVO LANÇAMENTO");
        }
 
        carregarCombos();
 
        if (modo.equals("SALVAR")) {
            limparCampos();
            cmbImovel.setEnabled(true);
            txtParcelas.setEnabled(true);
        } else {
            cmbImovel.setEnabled(false);
            txtParcelas.setEnabled(false);
            txtParcelas.setText("—");
        }
    }
    
    public void preencherCampos(LancamentoImposto lancamento) {
        if (lancamento.getImovel() != null) {
            for (int i = 0; i < listaImoveis.size(); i++) {
                if (listaImoveis.get(i).getId().equals(lancamento.getImovel().getId())) {
                    cmbImovel.setSelectedIndex(i);
                    break;
                }
            }
        }
 
        if (lancamento.getImposto() != null) {
            for (int i = 0; i < listaImpostos.size(); i++) {
                if (listaImpostos.get(i).getId().equals(lancamento.getImposto().getId())) {
                    cmbImposto.setSelectedIndex(i);
                    break;
                }
            }
        }
    }
    
    private void limparCampos() {
        if (cmbImovel.getItemCount() > 0) {
            cmbImovel.setSelectedIndex(0);
        }
        if (cmbImposto.getItemCount() > 0) {
            cmbImposto.setSelectedIndex(0);
        }
        txtParcelas.setText("1");
    }
    
    private void carregarCombos() {
        listaImoveis = imovelController.findByAtivoTrue();
        cmbImovel.removeAllItems();
 
        for (Imovel i : listaImoveis) {
            String bairro;
            if (i.getEndereco() != null) {
                bairro = i.getEndereco().getBairro();
            } else {
                bairro = "—";
            }
            cmbImovel.addItem(i.getInscricaoImobiliaria() + " | " + bairro);
        }
 
        listaImpostos = impostoController.findByAtivoTrue();
        cmbImposto.removeAllItems();
 
        for (Imposto imp : listaImpostos) {
            cmbImposto.addItem(imp.getDescricao() + " (" + imp.getAnoExercicio() + ")");
        }
    }
