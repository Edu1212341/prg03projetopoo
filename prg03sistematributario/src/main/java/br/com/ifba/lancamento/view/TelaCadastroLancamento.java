    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        try {
            if (listaImoveis.isEmpty() || cmbImovel.getSelectedIndex() < 0) {
                JOptionPane.showMessageDialog(this,
                        "Selecione um imóvel.",
                        "Campo obrigatório", JOptionPane.WARNING_MESSAGE);
                return;
            }
 
            if (listaImpostos.isEmpty() || cmbImposto.getSelectedIndex() < 0) {
                JOptionPane.showMessageDialog(this,
                        "Selecione um imposto.",
                        "Campo obrigatório", JOptionPane.WARNING_MESSAGE);
                return;
            }
 
            Imovel  imovelSelecionado  = listaImoveis.get(cmbImovel.getSelectedIndex());
            Imposto impostoSelecionado = listaImpostos.get(cmbImposto.getSelectedIndex());
 
            LancamentoImposto lancamento = new LancamentoImposto();
            lancamento.setImovel(imovelSelecionado);
            lancamento.setImposto(impostoSelecionado);
 
            if (modo.equals("EDITAR") && idEmEdicao != null) {
                lancamentoController.update(idEmEdicao, lancamento);
                JOptionPane.showMessageDialog(this, "Lançamento atualizado com sucesso!");
            } else {
                int parcelas = Integer.parseInt(txtParcelas.getText().trim());
                lancamentoController.save(lancamento, parcelas);
                JOptionPane.showMessageDialog(this,
                        "Lançamento registrado!\nBoletos gerados automaticamente.");
            }
 
            limparCampos();
            telaPrincipal.carregarTabela();
            this.dispose();
 
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "O número de parcelas deve ser um inteiro (ex: 1, 3, 12).",
                    "Valor inválido", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            log.warn("Erro ao salvar lançamento: {}", ex.getMessage());
            JOptionPane.showMessageDialog(this,
                    ex.getMessage(), "Erro ao Salvar", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

