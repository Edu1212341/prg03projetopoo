    public void setModo(String modo, Long id, GerenciarUsuarios principal) {
        this.modo = modo;
        this.idEmEdicao = id;
        this.telaPrincipal = principal;
        lblTitulo.setText(modo.equals("EDITAR") ? "EDITAR USUÁRIO" : "CADASTRAR USUÁRIO");
        if (modo.equals("SALVAR")) limparCampos();
        
        configurarPermissoesDeTela();
    }
    
    private void configurarPermissoesDeTela() {
        Usuario logado = sessaoService.getUsuarioLogado();
    
        //Se NÃO for admin, ele nunca pode mexer no ComboBox de nível de acesso
        if (!logado.getNivelAcesso().equals("ADMIN")) {
            cmbNivel.setEnabled(false); 
        } else {
            cmbNivel.setEnabled(true);
        }
    
        // Se o usuário estiver editando a SI MESMO 
        if (modo.equals("EDITAR") && idEmEdicao.equals(logado.getId())) {
            // Bloqueia tudo, menos a senha
            txtNome.setEnabled(false);
            txtLogin.setEnabled(false);
            cmbNivel.setEnabled(false); // Reforça o bloqueio do cargo
        } else {
            // Se for um Admin editando outra pessoa, libera os textos
            txtNome.setEnabled(true);
            txtLogin.setEnabled(true);
        }
    }
    private void limparCampos() {
        txtNome.setText("");
        txtLogin.setText("");
        pswSenha.setText("");
        cmbNivel.setSelectedIndex(0);
    }
    
    public void preencherCampos(String nome, String login, String nivel) {
        txtNome.setText(nome);
        txtLogin.setText(login);
        cmbNivel.setSelectedItem(nivel);
        
        // O campo de palavra-passe deve ficar limpo por questões de segurança.
        // O utilizador só preenche este campo se realmente quiser alterar a palavra-passe.
        pswSenha.setText("");
    }
