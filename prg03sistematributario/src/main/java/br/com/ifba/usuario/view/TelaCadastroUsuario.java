    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        try {
        // 1. Criamos um objeto apenas para agrupar os dados da tela
        Usuario dadosFormulario = new Usuario();
        dadosFormulario.setNome(txtNome.getText());
        dadosFormulario.setLogin(txtLogin.getText());
        dadosFormulario.setSenha(new String(pswSenha.getPassword()));
        dadosFormulario.setNivelAcesso((String) cmbNivel.getSelectedItem());

        if (modo.equals("EDITAR") && idEmEdicao != null) {
            // 2. Passamos o ID de controle e o pacote de dados para o controller
            usuarioController.update(idEmEdicao, dadosFormulario);
            JOptionPane.showMessageDialog(this, "Usuário atualizado com sucesso!");
        } else {
            // O cadastro do zero continua igual
            usuarioController.save(dadosFormulario);
            JOptionPane.showMessageDialog(this, "Usuário salvo!");
        }

        limparCampos();
        telaPrincipal.carregarTabela();
        this.dispose();

    } catch (Exception ex) {
        javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnSalvarActionPerformed

