    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblImpostos.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this,
                "Selecione um imposto na tabela para excluir.",
                "Nenhuma seleção", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // O ID está na coluna 5, e a Descrição está na coluna 0
        Long id = (Long) tblImpostos.getValueAt(linha, 5);
        String descricao = (String) tblImpostos.getValueAt(linha, 0);

        int confirmacao = JOptionPane.showConfirmDialog(
            this,
            "Tem certeza que deseja excluir o imposto:\n\"" + descricao + "\"?",
            "Confirmar Exclusão",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        if (confirmacao == JOptionPane.YES_OPTION) {
            try {
                impostoController.delete(id); // Corrigido para impostoController
                JOptionPane.showMessageDialog(this,
                    "Imposto excluído com sucesso!",
                    "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                tblImpostos.clearSelection();
                carregarTabela();

            } catch (Exception ex) {
                log.error("Erro ao excluir imposto ID {}: {}", id, ex.getMessage());
                JOptionPane.showMessageDialog(this,
                    ex.getMessage(),
                    "Erro ao Excluir", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        int linha = tblImpostos.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this,
                "Selecione um imposto na tabela para editar.",
                "Nenhuma seleção", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // O ID está na coluna 5
        Long id = (Long) tblImpostos.getValueAt(linha, 5);

        // Corrigido para buscar um Imposto através do impostoController
        Imposto imposto = impostoController.findById(id);

        telaCadastro.setModo("EDITAR", id, this);
        telaCadastro.preencherCampos(imposto);
        telaCadastro.setVisible(true);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String texto = txtBuscar.getText().trim();

        if (texto.isEmpty()) {
            carregarTabela();
            return;
        }

        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblImpostos.getModel();
        modelo.setRowCount(0);

        try {
            // Corrigido para usar impostoController e varrer Impostos
            for (Imposto imposto : impostoController.findByAtivoTrue()) {
                
                // Verifica se a descrição do imposto contém o texto buscado
                if (imposto.getDescricao().toLowerCase().contains(texto.toLowerCase())) {
                    
                    String aliquotaTerrenoStr;
                    String aliquotaConstrucaoStr;
                    String tipoImposto;

                    // IF expandido para verificar se é IPTU e extrair dados específicos
                    if (imposto instanceof ImpostoIPTU) {
                        ImpostoIPTU iptu = (ImpostoIPTU) imposto;
                        aliquotaTerrenoStr = String.valueOf(iptu.getAliquotaTerreno());
                        aliquotaConstrucaoStr = String.valueOf(iptu.getAliquotaConstrucao());
                        tipoImposto = "IPTU";
                    } else {
                        aliquotaTerrenoStr = "-";
                        aliquotaConstrucaoStr = "-";
                        tipoImposto = "Geral";
                    }

                    modelo.addRow(new Object[]{
                        imposto.getDescricao(),
                        imposto.getAnoExercicio(),
                        tipoImposto,
                        aliquotaTerrenoStr,
                        aliquotaConstrucaoStr,
                        imposto.getId()
                    });
                }
            }

            if (modelo.getRowCount() == 0) {
                JOptionPane.showMessageDialog(this,
                    "Nenhum imposto encontrado para: \"" + texto + "\".",
                    "Busca sem resultado", JOptionPane.INFORMATION_MESSAGE);
            }

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this,
                "Erro ao buscar: " + ex.getMessage(),
                "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

