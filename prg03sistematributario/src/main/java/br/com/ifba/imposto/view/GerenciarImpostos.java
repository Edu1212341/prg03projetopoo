    public void carregarTabela() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblImpostos.getModel();
        modelo.setRowCount(0); // Limpa a tabela

        try {
            for (Imposto imposto : impostoController.findByAtivoTrue()) {
                
                // Variáveis STR (strings) para carregar a tabela
                String aliquotaTerrenoStr;
                String aliquotaConstrucaoStr;
                String tipoImposto;

                // Verifica, usando IF expandido, se o imposto que veio do banco é um IPTU
                if (imposto instanceof ImpostoIPTU) {
                    ImpostoIPTU iptu = (ImpostoIPTU) imposto;
                    aliquotaTerrenoStr = String.valueOf(iptu.getAliquotaTerreno());
                    aliquotaConstrucaoStr = String.valueOf(iptu.getAliquotaConstrucao());
                    tipoImposto = "IPTU";
                } else {
                    aliquotaTerrenoStr = "-";
                    aliquotaConstrucaoStr = "-";
                    tipoImposto = "Geral";
                }
                
                // Adiciona a linha na tabela (Lembre-se de configurar essas 6 colunas no Design do NetBeans!)
                modelo.addRow(new Object[]{
                    imposto.getDescricao(),
                    imposto.getAnoExercicio(),
                    tipoImposto,
                    aliquotaTerrenoStr,
                    aliquotaConstrucaoStr,
                    imposto.getId()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar tabela: " + e.getMessage());
        }
    }

