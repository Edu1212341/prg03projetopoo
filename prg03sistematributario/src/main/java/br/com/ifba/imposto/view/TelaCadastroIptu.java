    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        try {
            ImpostoIPTU iptu = new ImpostoIPTU();
            iptu.setDescricao(txtDescricao.getText());
            iptu.setAnoExercicio(Integer.parseInt(txtAnoExercicio.getText().trim()));
            iptu.setAliquotaTerreno(Double.parseDouble(txtAliquotaTerreno.getText().replace(",", ".")));
            iptu.setAliquotaConstrucao(Double.parseDouble(txtAliquotaConstrucao.getText().replace(",", ".")));

            if (modo.equals("EDITAR") && idEmEdicao != null) {
                impostoController.update(idEmEdicao, iptu);
                JOptionPane.showMessageDialog(this, "IPTU atualizado com sucesso!");
            } else {
                impostoController.save(iptu);
                JOptionPane.showMessageDialog(this, "IPTU cadastrado com sucesso!");
            }

            limparCampos();
            telaPrincipal.carregarTabela();
            this.dispose();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                "Ano e alíquotas devem ser números válidos.",
                "Valor inválido", javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            log.warn("Erro ao salvar IPTU: {}", ex.getMessage());
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro ao Salvar", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

