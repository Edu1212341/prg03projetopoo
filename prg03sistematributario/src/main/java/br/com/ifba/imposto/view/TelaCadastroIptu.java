    public void setModo(String modo, Long id, GerenciarImpostos principal) {
        this.modo = modo;
        this.idEmEdicao = id;
        this.telaPrincipal = principal;
        
        if (modo.equals("EDITAR")) {
            lblTitulo.setText("EDITAR IPTU");
        } else {
            lblTitulo.setText("CADASTRAR IPTU");
        }
 
        if (modo.equals("SALVAR")) {
            limparCampos();
        }
    }
    
    public void preencherCampos(Imposto imposto) {
        txtDescricao.setText(imposto.getDescricao());
        txtAnoExercicio.setText(String.valueOf(imposto.getAnoExercicio()));
 
        // IF expandido: Só preenche as alíquotas se o imposto realmente for um IPTU
        if (imposto instanceof ImpostoIPTU) {
            ImpostoIPTU iptu = (ImpostoIPTU) imposto;
            txtAliquotaTerreno.setText(String.valueOf(iptu.getAliquotaTerreno()));
            txtAliquotaConstrucao.setText(String.valueOf(iptu.getAliquotaConstrucao()));
        } else {
            txtAliquotaTerreno.setText("");
            txtAliquotaConstrucao.setText("");
        }
    }
    
    private void limparCampos() {
        txtDescricao.setText("");
        txtAnoExercicio.setText("");
        txtAliquotaTerreno.setText("");
        txtAliquotaConstrucao.setText("");
    }
